create table if not exists public.routes (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 60),
  skills text not null default '' check (char_length(skills) <= 250),
  distance_km double precision not null check (distance_km between 0.05 and 150),
  duration_minutes integer not null default 0 check (duration_minutes between 0 and 300),
  points jsonb not null,
  created_at timestamptz not null default now()
);

alter table public.routes enable row level security;

create policy "Anyone can read practice routes"
on public.routes for select
to anon, authenticated
using (true);

create policy "Anyone can submit a practice route"
on public.routes for insert
to anon, authenticated
with check (
  jsonb_typeof(points) = 'array'
  and jsonb_array_length(points) between 2 and 1200
);

-- No update or delete policy is intentional. Until owner authentication is
-- added, remove unwanted routes safely in the Supabase table editor.
